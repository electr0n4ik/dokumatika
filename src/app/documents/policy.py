# --------------------------------------------------------------------- условия


def _data(kind: str) -> Condition:
    """Пользователь отметил такой тип данных на третьем шаге визарда."""
    return Condition("data_types", "contains", kind)


def _purpose(kind: str) -> Condition:
    return Condition("purposes", "contains", kind)


def _resource(kind: str) -> Condition:
    return Condition("resource", "eq", kind)


