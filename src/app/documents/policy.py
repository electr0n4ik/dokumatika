"""Шаблон политики в отношении обработки персональных данных.

Флагманский бесплатный документ сайта. Структура следует части 2 статьи 18.1
и статье 14 Федерального закона от 27.07.2006 № 152-ФЗ: без раздела о правах
субъекта, мерах защиты и порядке обращения политика формально неполна, поэтому
такие пункты помечены ``required_by_law=True`` — их нельзя выключить условием.

Важное решение по вёрстке: **один ``Clause`` = один пронумерованный раздел**,
и у каждого есть заголовок. Нумерация в ``RenderedDocument.plain_text`` идёт по
порядковому номеру пункта, а печатается только при непустом заголовке — пункт
без заголовка «съел» бы номер и оставил дыру в нумерации документа. Поэтому
условные уточнения оформлены не подпунктами, а самостоятельными разделами со
своими заголовками.

Второе решение: варианты, зависящие от ответа (например, реквизиты с ОГРН и
без него), сделаны взаимоисключающими парами пунктов, а не одним пунктом с
плейсхолдером-прочерком. Прочерк в графе «ОГРН» у самозанятого выглядит как
незаполненный документ, хотя ОГРН у него и не может быть.
"""

