"""Семь шаблонов платного комплекта по 152-ФЗ.

Ради этих документов человек платит 799 ₽, поэтому здесь нет «рыбы»: каждый
пункт либо требуется законом, либо снимает конкретный вопрос покупателя.

Три соглашения, которых стоит держаться при правке:

1. **В одном документе либо все пункты с заголовками, либо ни одного.**
   Текстовый рендер нумерует пункты сквозным счётчиком, но печатает номер
   только у озаглавленных. Смешивать нельзя — в нумерации появятся дыры.
   Формы (приказ, бланк отзыва) идут без заголовков, там своя вёрстка.
2. **Первая строка ``rows`` — шапка таблицы.** Схема не различает заголовок и
   данные, договорённость держится соглашением.
3. **Условные пункты дублируются целиком, а не по абзацам.** Условие живёт на
   пункте, поэтому вариант «для организации» и «для ИП» — это два ``Clause`` с
   одинаковым заголовком и разными ``when``. Ветвление внутри абзаца невозможно
   намеренно: язык условий примитивен ровно для того, чтобы Python и JS не
   разошлись.

Все цифры и ссылки на нормы — из ``docs/fakty-152-fz.md``. Документы типовые:
они не заменяют юриста и нигде этого не обещают.
"""

