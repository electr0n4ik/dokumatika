PASSPORT: tuple[Condition, ...] = (Condition("data_types", "contains", "passport"),)
PHOTO: tuple[Condition, ...] = (Condition("data_types", "contains", "photo"),)

CROSS_BORDER: tuple[Condition, ...] = (Condition("cross_border"),)
NO_CROSS_BORDER: tuple[Condition, ...] = (Condition("cross_border", "falsy"),)

# RU: «Никому не передаю» — тоже отмеченный вариант, поэтому одной проверки на
# непустоту мало.
HAS_THIRD_PARTIES: tuple[Condition, ...] = (
    Condition("third_parties"),
    Condition("third_parties", "not_contains", "none"),
)
ANALYTICS_SERVICE: tuple[Condition, ...] = (
    Condition("third_parties", "contains", "analytics_service"),
)

# RU: Строка-подчёркивание одна на все бланки — иначе они разной длины и
