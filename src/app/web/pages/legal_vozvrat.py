def build(ctx: PageContext) -> tuple[PageMeta, Raw]:
    site = ctx.site
    crumbs = (Crumb("Главная", "/"), Crumb("Возврат и отказ от услуги"))

    warn = Raw("")
    if not site.seller.is_complete:
        warn = callout(
            "Реквизиты продавца не заполнены",
            "Заполните переменные SELLER_* в .env до подключения приёма оплаты: сейчас вместо "
            "данных продавца на странице стоят прочерки.",
            tone="warn",
        )

    articles = join(
        [
            _article(number, title, items, extra, anchor=anchor)
            for number, (title, items, extra, anchor) in enumerate(_articles(ctx), start=1)
        ]
    )
    faq = _faq(ctx)

    body = join(
        [
            breadcrumbs(crumbs),
            Raw("<h1>Возврат и отказ от услуги</h1>"),
            author_meta(UPDATED),
            warn,
            tldr(
                "Доступ к комплекту открывается сразу после оплаты, поэтому применяется ст. 32 "
                "ЗоЗПП — отказ от услуги с возмещением фактических расходов. Если оплата прошла, а "
                "доступ не открылся, или деньги списались дважды — возвращаем всю сумму."
            ),
            articles,
            faq_block(faq),
            Raw(f'<p class="requisites">Продавец: {esc(_seller_line(site.seller))}</p>'),
            legal_note(site.legal_note),
            cross_links(
                (
                    ("Публичная оферта", "Полные условия договора", "/oferta/"),
                    ("Контакты", "Куда писать и когда ответим", "/kontakty/"),
                    ("Политика конфиденциальности", "Что мы делаем с вашим email", "/privacy/"),
                ),
                title="Связанные документы",
            ),
        ]
    )

    meta = PageMeta(
        path="/vozvrat/",
        title="Возврат и отказ от услуги",
        description=(
            "Возврат оплаты за комплект документов: когда вернём всю сумму, как подать заявление, "
            "сроки рассмотрения и зачисления. Отказ от услуги по ст. 32 ЗоЗПП."
        ),
        h1="Возврат и отказ от услуги",
        updated=UPDATED,
        crumbs=crumbs,
        faq=faq,
    )
    return meta, body


PAGE = Page(path="/vozvrat/", build=build, changefreq="yearly", priority="0.3")
