def _value(text: str) -> str:
    return text.strip() or BLANK


def _seller_line(seller: SellerConfig) -> str:
    """Однострочные реквизиты: «Самозанятый ФИО, ИНН, город» — формат платёжного сервиса."""
    if not seller.is_complete:
        return f"{BLANK}, ИНН {BLANK}, {BLANK}"
    parts = [seller.display_name, f"ИНН {seller.inn}"]
    if seller.address:
        parts.append(seller.address)
    return ", ".join(parts)


def _article(
    number: int,
    title: str,
    items: tuple[Raw | str, ...],
    extra: Raw | str = "",
    *,
    anchor: str = "",
) -> Raw:
    clauses = join(
        [Raw(f"<p>{number}.{index}. {esc(text)}</p>") for index, text in enumerate(items, start=1)]
    )
    return section(title=f"{number}. {title}", body=join([clauses, extra]), anchor=anchor)


