        "назначении ответственного, форма отзыва, журнал обращений и памятка по уведомлению в "
        "Роскомнадзор. Сама политика у нас "
        '<a href="/">бесплатна</a> и в комплект не входит. Документы собираются по вашим ответам '
        "в браузере и доступны сразу после оплаты. Зачем это нужно: с 01.09.2025 согласие нельзя "
        "держать пунктом в оферте (ч. 1 ст. 9 152-ФЗ), а за неподанное уведомление в РКН ч. 10 "
        "ст. 13.11 КоАП даёт 30 000–50 000 ₽ должностным лицам и ИП и 100 000–300 000 ₽ юрлицам."
