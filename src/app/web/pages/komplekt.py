def _paragraphs(*items: object) -> Raw:
    return join([Raw(f"<p>{esc(item)}</p>") for item in items])


def _bullets(items: tuple[str, ...]) -> Raw:
    return Raw(f"<ul>{esc(join([Raw(f'<li>{esc(item)}</li>') for item in items]))}</ul>")


def _documents_table(includes: tuple[str, ...]) -> Raw:
    rows = tuple((title, DOC_NOTES.get(title, "Входит в комплект")) for title in includes)
    return comparison_table(("Документ", "Что он закрывает"), rows)


def _order_form(ctx: PageContext) -> Raw:
    """Форма заказа.

    Разметка статическая: JS перехватывает submit и уходит на ``/api/order``.
    Три чекбокса раздельные и непредустановленные — согласие на обработку,
    принятие оферты и рассылка. Слитая «галочка на всё» не доказывает ничего,
    а факт принятия оферты — единственный аргумент при чарджбэке.
    """
    if not ctx.payments_enabled:
        return Raw(f'<p class="price-disabled">{esc(ctx.checkout_disabled_note)}</p>')

    support = ctx.site.support_email
    fallback = (
        f' Или напишите на <a href="mailto:{esc(support)}">{esc(support)}</a> — ответим и оформим '
        "заказ вручную."
        if support
        else ""
    )
    return Raw(
        '<form class="orderform" id="order-form" method="post" action="/api/order" novalidate>'
        '<div class="field">'
        '<label for="order-email">Электронная почта</label>'
        '<input id="order-email" type="email" name="email" autocomplete="email" inputmode="email" '
        'maxlength="254" required placeholder="vy@example.ru">'
        '<p class="hint">На этот адрес придёт ссылка на документы. Ничего другого не присылаем.</p>'
        "</div>"
        '<label class="check"><input type="checkbox" name="accept_privacy" value="1" required>'
        "<span>Даю согласие на обработку персональных данных на условиях "
        '<a href="/privacy/">политики конфиденциальности</a></span></label>'
        '<label class="check"><input type="checkbox" name="accept_offer" value="1" required>'
        '<span>Принимаю условия <a href="/oferta/">публичной оферты</a> и согласен, что доступ к '
        "документам открывается сразу после оплаты</span></label>"
        '<label class="check"><input type="checkbox" name="accept_marketing" value="1">'
        "<span>Хочу изредка получать письма об изменениях в 152-ФЗ (необязательно)</span></label>"
        f'<button class="btn btn-p btn-wide" type="submit">Оплатить {esc(ctx.product.price_label)}'
        "</button>"
        '<p class="formstatus" id="order-status" role="status" aria-live="polite"></p>'
        "</form>"
        "<noscript><p><strong>Для оформления заказа нужен JavaScript.</strong> Кнопка выше "
        f"передаёт заказ платёжному сервису скриптом, без него форма не сработает.{fallback}</p>"
        "</noscript>"
    )


