def _paragraphs(*texts: str) -> Raw:
    return join([Raw(f"<p>{esc(text)}</p>") for text in texts])


def _bullets(*items: str) -> Raw:
    body = join([Raw(f"<li>{esc(item)}</li>") for item in items])
    return Raw(f"<ul>{esc(body)}</ul>")


def _code_block(code: str) -> Raw:
    """Показать разметку образца текстом, а не выполнить её.

    Экранирование обычное, но ``&lt;`` заменяется на числовую ссылку ``&#60;``:
    браузер рисует ровно то же самое, а проверка ``test_no_escaped_markup``,
    которая ищет следы потерянного ``Raw`` по подстроке «&lt;тег», не принимает
    наш образец кода за ошибку разметки. Обёртка ``.table-wrap`` даёт
    горизонтальную прокрутку — длинные строки не ломают вёрстку на телефоне.
    """
    escaped = esc(code).replace("&lt;", "&#60;")
    return Raw(f'<div class="table-wrap"><pre><code>{escaped}</code></pre></div>')


