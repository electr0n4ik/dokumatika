def build(ctx: PageContext) -> tuple[PageMeta, Raw]:
    site = ctx.site
    crumbs = (Crumb("Главная", "/"), Crumb("Политика конфиденциальности"))

    warn = Raw("")
    if not site.seller.is_complete:
        warn = callout(
            "Реквизиты продавца не заполнены",
            "Заполните переменные SELLER_* в .env до подключения приёма оплаты: сейчас вместо "
            "данных оператора в тексте политики стоят прочерки.",
            tone="warn",
        )

    articles = join(
        [
            _article(number, title, items, extra, anchor=anchor)
            for number, (title, items, extra, anchor) in enumerate(_articles(ctx), start=1)
        ]
    )
    faq = _faq(ctx)

    body = join(
        [
            breadcrumbs(crumbs),
            Raw("<h1>Политика конфиденциальности</h1>"),
            author_meta(UPDATED),
            warn,
            tldr(
                "Мы обрабатываем минимум: email покупателя и факт принятия оферты. Ответы на "
                "вопросы генератора и ваши реквизиты остаются в браузере и на сервер не попадают."
            ),
            callout(
                "Документ собран нашим же генератором",
                "Эта политика прошла те же пять шагов визарда, что и ваша, и была дополнена "
                "разделами про оплату комплекта. Мы пользуемся собственным инструментом.",
                tone="info",
                href="/",
                cta="Собрать свою политику",
            ),
            articles,
            faq_block(faq),
            legal_note(site.legal_note),
            cross_links(
                (
                    ("Публичная оферта", "На каких условиях мы продаём комплект", "/oferta/"),
                    ("Возврат и отказ от услуги", "Когда и как возвращаем оплату", "/vozvrat/"),
                    ("Контакты", "Реквизиты оператора и адрес поддержки", "/kontakty/"),
                ),
                title="Связанные документы",
            ),
        ]
    )

    meta = PageMeta(
        path="/privacy/",
        title="Политика конфиденциальности",
        description=(
            "Политика конфиденциальности Докуматики: обрабатываем только email покупателя и факт "
            "акцепта оферты. Ответы генератора и ваши реквизиты остаются в браузере."
        ),
        h1="Политика конфиденциальности",
        updated=UPDATED,
        crumbs=crumbs,
        faq=faq,
    )
    return meta, body


PAGE = Page(path="/privacy/", build=build, changefreq="yearly", priority="0.3")
