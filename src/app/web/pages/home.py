def _paragraphs(*items: object) -> Raw:
    return join([Raw(f"<p>{esc(item)}</p>") for item in items])


def _wizard_mount() -> Raw:
    """Точка монтирования визарда.

    Внутри — только noscript: всё остальное дорисует ``wizard.js``. Заглушку
    держим внутри контейнера, чтобы скрипт затирал её вместе с содержимым.
    """
    return Raw(
        '<div id="wizard-app" class="wizard-mount">'
        "<noscript>"
        "<p><strong>Конструктору нужен JavaScript.</strong> Документ собирается прямо в вашем "
        "браузере — именно поэтому ответы никуда не отправляются. Включите JavaScript и обновите "
        "страницу.</p>"
        "<p>Остальные разделы страницы читаются и без скриптов: ниже разобрано, что закон требует "
        "от владельца сайта и что входит в политику.</p>"
        "</noscript>"
        "</div>"
    )


