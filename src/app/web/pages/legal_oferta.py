def _value(text: str) -> str:
    return text.strip() or BLANK


def _seller_title(seller: SellerConfig) -> str:
    return seller.display_name if seller.is_complete else BLANK


def _requisites(seller: SellerConfig) -> Raw:
    rows: list[tuple[str, str]] = [
        ("Продавец", _seller_title(seller)),
        ("ИНН", _value(seller.inn)),
    ]
    if seller.ogrn:
        rows.append(("ОГРНИП", seller.ogrn))
    rows.append(("Электронная почта", _value(seller.email)))
    rows.append(("Адрес", _value(seller.address)))
    body = join([Raw(f"<div><dt>{esc(name)}</dt><dd>{esc(value)}</dd></div>") for name, value in rows])
    return Raw(f'<dl class="requisites">{esc(body)}</dl>')


def _article(
    number: int,
    title: str,
    items: tuple[Raw | str, ...],
    extra: Raw | str = "",
    *,
    anchor: str = "",
) -> Raw:
    """Раздел договора с автонумерацией пунктов: 4.1, 4.2 и так далее."""
    clauses = join(
        [Raw(f"<p>{number}.{index}. {esc(text)}</p>") for index, text in enumerate(items, start=1)]
    )
    return section(title=f"{number}. {title}", body=join([clauses, extra]), anchor=anchor)


