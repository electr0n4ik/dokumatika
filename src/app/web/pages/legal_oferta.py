def build(ctx: PageContext) -> tuple[PageMeta, Raw]:
    site = ctx.site
    product = ctx.product
    crumbs = (Crumb("Главная", "/"), Crumb("Публичная оферта"))

    warn = Raw("")
    if not site.seller.is_complete:
        warn = callout(
            "Реквизиты продавца не заполнены",
            "Заполните переменные SELLER_* в .env до подключения приёма оплаты: сейчас в тексте "
            "оферты стоят прочерки вместо данных продавца.",
            tone="warn",
        )

    paused = Raw("")
    if not ctx.payments_enabled:
        paused = callout("Приём оплаты приостановлен", ctx.checkout_disabled_note, tone="warn")

    articles = join(
        [
            _article(number, title, items, extra, anchor=anchor)
            for number, (title, items, extra, anchor) in enumerate(_articles(ctx), start=1)
        ]
    )

    body = join(
        [
            breadcrumbs(crumbs),
            Raw("<h1>Публичная оферта</h1>"),
            author_meta(UPDATED),
            warn,
            paused,
            tldr(
                f"Это договор между вами и продавцом. Оплата комплекта «{product.title}» за "
                f"{product.price_label} означает согласие с условиями ниже. Доступ к документам "
                "открывается сразу после подтверждения оплаты, поэтому порядок возврата описан "
                "отдельно."
            ),
            articles,
            legal_note(site.legal_note),
            cross_links(
                (
                    ("Возврат и отказ от услуги", "Когда вернём деньги и как подать заявление", "/vozvrat/"),
                    ("Политика конфиденциальности", "Какие данные мы обрабатываем и зачем", "/privacy/"),
                    ("Контакты", "Реквизиты продавца и адрес поддержки", "/kontakty/"),
                ),
                title="Связанные документы",
            ),
        ]
    )

    meta = PageMeta(
        path="/oferta/",
        title="Публичная оферта",
        description=(
            f"Публичная оферта сервиса Докуматика: предмет договора, цена {product.price_label}, "
            "порядок оплаты и предоставления доступа, ограничение ответственности и возврат."
        ),
        h1="Публичная оферта",
        updated=UPDATED,
        crumbs=crumbs,
    )
    return meta, body


PAGE = Page(path="/oferta/", build=build, changefreq="yearly", priority="0.3")
