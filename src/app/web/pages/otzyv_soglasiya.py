def _p(*parts: object) -> Raw:
    return Raw("<p>" + "".join(esc(part) for part in parts) + "</p>")


def _ul(items: tuple[object, ...]) -> Raw:
    return Raw("<ul>" + join([Raw(f"<li>{esc(item)}</li>") for item in items]) + "</ul>")


def _sample(blocks: tuple[tuple[str, tuple[str, ...], str], ...]) -> Raw:
    parts: list[str] = []
    for title, paragraphs, hint in blocks:
        parts.append(f"<h3>{esc(title)}</h3>")
        parts.extend(f"<p>{esc(text)}</p>" for text in paragraphs)
        if hint:
            parts.append(f'<p class="note">{esc(hint)}</p>')
    return Raw(f'<div class="doc-preview">{join(parts)}</div>')


