def _paragraphs(*texts: str) -> Raw:
    return join([Raw(f"<p>{esc(text)}</p>") for text in texts])


def _bullets(*items: str) -> Raw:
    body = join([Raw(f"<li>{esc(item)}</li>") for item in items])
    return Raw(f"<ul>{esc(body)}</ul>")


