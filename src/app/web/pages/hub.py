def _bullets(items: tuple[str, ...]) -> Raw:
    return Raw(f"<ul>{esc(join([Raw(f'<li>{esc(item)}</li>') for item in items]))}</ul>")


def build(ctx: PageContext) -> tuple[PageMeta, Raw]:
    summary = Raw(
        "Сайту с формой заявки, подпиской или счётчиком аналитики закон отводит роль оператора "
        "персональных данных — и вместе с ней девять обязанностей. Минимум: опубликовать политику "
        "(ч. 2 ст. 18.1), взять согласие отдельным документом (с 01.09.2025, ч. 1 ст. 9), "
        "назначить ответственного (п. 1 ч. 1 ст. 18.1) и подать уведомление в Роскомнадзор до "
        "начала обработки (ч. 1 ст. 22). Цена бездействия по ст. 13.11 КоАП: 6 000–12 000 ₽ "
        "должностным лицам и ИП за отсутствие политики и 30 000–50 000 ₽ за неподанное "
        "уведомление; для юрлиц — до 60 000 ₽ и до 300 000 ₽ соответственно. Ниже чек-лист: "
        'каждый пункт со ссылкой на то, чем он закрывается, начиная с '
        '<a href="/">бесплатной политики</a>.'
    )

    fines_table = comparison_table(FINE_HEADERS, FINE_ROWS, caption="Штрафы по ст. 13.11 КоАП")
    fines = section(
        "Сколько стоит не сделать",
        join([fines_table, _bullets(FINE_NOTES)]),
        anchor="shtrafy",
        lead=FINES_LEAD,
    )
    deadlines = section(
        "Сроки, которые легко пропустить",
        comparison_table(DEADLINE_HEADERS, DEADLINE_ROWS),
        anchor="sroki",
    )
    checklist = section(
        "Чек-лист: девять шагов к соответствию",
        steps_list(CHECKLIST),
        anchor="cheklist",
        lead=CHECKLIST_LEAD,
    )
    start = callout(
        "Начните с бесплатного",
        "Политика конфиденциальности собирается на главной за пять шагов и ничего не стоит. "
        "Остальные документы из чек-листа — согласия, cookie, приказ, журнал обращений и памятка "
        f"по уведомлению в Роскомнадзор — собраны в комплекте за {ctx.product.price_label}.",
        tone="info",
        href="/komplekt/",
        cta="Посмотреть комплект",
    )

    meta = PageMeta(
        path="/152-fz-dlya-sayta/",
        title="152-ФЗ для сайта: что нужно сделать в 2026 году",
        description=(
            "Чек-лист требований 152-ФЗ к сайту: политика, отдельное согласие, уведомление в "
            "Роскомнадзор, ответственный, cookie и штрафы по ст. 13.11 КоАП."
        ),
        h1=H1,
        updated=UPDATED,
        og_type="article",
        crumbs=CRUMBS,
        faq=FAQ,
    )

    body = Raw(
        f"{esc(breadcrumbs(CRUMBS))}"
        f"<h1>{esc(H1)}</h1>"
        f"{esc(tldr(summary))}"
        f"{esc(author_meta(UPDATED))}"
        f"{esc(checklist)}"
        f"{esc(start)}"
        f"{esc(fines)}"
        f"{esc(deadlines)}"
        f"{esc(faq_block(FAQ))}"
        f"{esc(cross_links(CROSS_LINKS))}"
        f"{esc(legal_note(ctx.site.legal_note))}"
    )
    return meta, body


